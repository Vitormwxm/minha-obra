CREATE TABLE app_account (
    id UUID PRIMARY KEY,
    username VARCHAR(40) NOT NULL UNIQUE,
    display_name VARCHAR(120) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL CHECK (role IN ('ADMIN','USER')),
    status VARCHAR(10) NOT NULL CHECK (status IN ('ACTIVE','BLOCKED')),
    must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
    auth_version BIGINT NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    totp_secret TEXT,
    totp_pending_secret TEXT,
    totp_pending_until TIMESTAMP WITH TIME ZONE,
    totp_last_counter BIGINT NOT NULL DEFAULT -1,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (username ~ '^[a-z0-9][a-z0-9._-]{2,39}$'),
    CHECK (role = 'ADMIN' OR (totp_secret IS NULL AND totp_pending_secret IS NULL))
);

CREATE TABLE account_recovery_code (
    account_id UUID NOT NULL REFERENCES app_account(id) ON DELETE CASCADE,
    code_hash CHAR(64) NOT NULL,
    PRIMARY KEY (account_id,code_hash)
);

CREATE TABLE account_idempotency (
    actor_id UUID NOT NULL REFERENCES app_account(id) ON DELETE CASCADE,
    operation VARCHAR(100) NOT NULL,
    request_key UUID NOT NULL,
    request_fingerprint CHAR(64) NOT NULL,
    response_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (actor_id,operation,request_key)
);
CREATE INDEX account_idempotency_expiration ON account_idempotency(created_at);

CREATE TABLE account_audit (
    id UUID PRIMARY KEY,
    actor_id UUID,
    account_id UUID NOT NULL,
    event_type VARCHAR(80) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE account_outbox (
    id UUID PRIMARY KEY REFERENCES account_audit(id),
    event_key UUID NOT NULL,
    event_type VARCHAR(80) NOT NULL,
    payload TEXT NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP WITH TIME ZONE,
    attempts INTEGER NOT NULL DEFAULT 0,
    available_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX account_outbox_pending ON account_outbox(available_at,occurred_at) WHERE published_at IS NULL;

CREATE TABLE SPRING_SESSION (
    PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY,
    SESSION_ID CHAR(36) NOT NULL,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INTEGER NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(100)
);
CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION(SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION(EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION(PRINCIPAL_NAME);
CREATE TABLE SPRING_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BYTEA NOT NULL,
    PRIMARY KEY (SESSION_PRIMARY_ID,ATTRIBUTE_NAME)
);
